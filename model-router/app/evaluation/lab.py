"""Multi-Model Evaluation Laboratory (M3.9).

M3.9 DEFINES EXPERIMENT ORCHESTRATION. IT DOES NOT EVALUATE ANSWER QUALITY.
----------------------------------------------------------------------------
An EvaluationExperiment defines:
- One common evaluation task
- Multiple model/provider candidates
- Metadata for experiment configuration
- EvaluationSummary generated by EvaluationRunner

SAME TASK GUARANTEE:
--------------------
All candidates in an experiment receive the exact same EvaluationTask definition:
- same input
- same expected_output
- same input_modalities
- same output_modalities
- same structured_output setting

EXAMPLE EXPERIMENT SCENARIO:
----------------------------
Experiment:
    experiment_id = "investment-analysis-v1"

Task:
    "Analyze this investment scenario."

Candidates:
    Candidate A:
        candidate_id = "cand-deepseek-openrouter"
        model_id = "deepseek/deepseek-chat"
        provider_id = "openrouter"

    Candidate B:
        candidate_id = "cand-llama-openrouter"
        model_id = "meta-llama/llama-3.3-70b-instruct"
        provider_id = "openrouter"

    Candidate C:
        candidate_id = "cand-deepseek-nim"
        model_id = "deepseek/deepseek-chat"
        provider_id = "nim"

Laboratory Execution:
    The laboratory runs the same task against every candidate and collects
    the normalized results into an ExperimentRunResult.
    It does NOT determine which result is better.

Future M3.10+ evaluation logic will score results and select a winner:
    ExperimentRunResult -> Evaluator -> Scores -> Winner
"""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator

from .runner import EvaluationRunner
from .schema import (
    EvaluationCandidate,
    EvaluationSummary,
    EvaluationTask,
)
from .validation import (
    InvalidEvaluationCandidateError,
    InvalidEvaluationExperimentError,
    InvalidExperimentRunResultError,
    validate_evaluation_candidate,
    validate_evaluation_summary,
    validate_evaluation_task,
)


class EvaluationExperiment(BaseModel):
    """Specification of a multi-model evaluation experiment."""

    model_config = ConfigDict(extra="forbid")

    experiment_id: str = Field(..., description="Explicit, human-controlled identifier for the experiment.")
    task: EvaluationTask = Field(..., description="The common evaluation task shared by all candidates.")
    candidates: list[EvaluationCandidate] = Field(
        default_factory=list,
        description="List of candidate model/provider configurations to evaluate.",
    )
    metadata: dict[str, str] = Field(
        default_factory=dict,
        description="Experiment-level configuration metadata.",
    )

    @field_validator("experiment_id")
    @classmethod
    def validate_experiment_id(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("experiment_id cannot be empty.")
        return v.strip()

    @field_validator("candidates")
    @classmethod
    def validate_candidates(cls, v: list[EvaluationCandidate]) -> list[EvaluationCandidate]:
        seen = set()
        for c in v:
            if c.candidate_id in seen:
                raise ValueError(f"Duplicate candidate_id detected: '{c.candidate_id}'.")
            seen.add(c.candidate_id)
        return v


class ExperimentRunResult(BaseModel):
    """Result of executing an EvaluationExperiment."""

    model_config = ConfigDict(extra="forbid")

    experiment_id: str = Field(..., description="Identifier of the executed experiment.")
    summary: EvaluationSummary = Field(..., description="Evaluation summary containing candidate execution results.")
    metadata: dict[str, str] = Field(
        default_factory=dict,
        description="Run-level result metadata.",
    )

    @field_validator("experiment_id")
    @classmethod
    def validate_experiment_id(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("experiment_id cannot be empty.")
        return v.strip()


def validate_evaluation_experiment(experiment: EvaluationExperiment) -> EvaluationExperiment:
    """Validate that an EvaluationExperiment satisfies contract invariants."""
    if not isinstance(experiment, EvaluationExperiment):
        raise InvalidEvaluationExperimentError(
            f"Expected EvaluationExperiment instance, got {type(experiment).__name__}."
        )
    if not experiment.experiment_id or not experiment.experiment_id.strip():
        raise InvalidEvaluationExperimentError("experiment_id cannot be empty.")

    validate_evaluation_task(experiment.task)

    seen: set[str] = set()
    for c in experiment.candidates:
        validate_evaluation_candidate(c)
        if c.candidate_id in seen:
            raise InvalidEvaluationCandidateError(
                f"Duplicate candidate_id detected: '{c.candidate_id}'."
            )
        seen.add(c.candidate_id)

    return experiment


def validate_experiment_run_result(result: ExperimentRunResult) -> ExperimentRunResult:
    """Validate that an ExperimentRunResult satisfies contract invariants."""
    if not isinstance(result, ExperimentRunResult):
        raise InvalidExperimentRunResultError(
            f"Expected ExperimentRunResult instance, got {type(result).__name__}."
        )
    if not result.experiment_id or not result.experiment_id.strip():
        raise InvalidExperimentRunResultError("experiment_id cannot be empty.")

    validate_evaluation_summary(result.summary)
    return result


class ModelLaboratory:
    """Laboratory orchestrator for multi-model evaluation experiments.

    Delegates execution to an injected EvaluationRunner while guaranteeing
    that all candidates are evaluated against the exact same EvaluationTask definition.
    """

    def __init__(self, runner: EvaluationRunner) -> None:
        if runner is None or not (
            isinstance(runner, EvaluationRunner)
            or (hasattr(runner, "run") and callable(getattr(runner, "run")))
        ):
            raise TypeError(
                f"ModelLaboratory requires an EvaluationRunner instance, got {type(runner).__name__}."
            )
        self.runner = runner

    def run(self, experiment: EvaluationExperiment) -> ExperimentRunResult:
        """Run all candidates in the experiment against the common task.

        Guarantees:
        - Same Task Guarantee: Every candidate is executed against the exact same task.
        - Immutability: The experiment, task, and candidates are never mutated.
        - Deterministic Order: Preserves candidate order.
        - Failure Isolation: Delegated to EvaluationRunner.
        - Quality Boundary: scores remain empty, winner remains None.
        """
        validate_evaluation_experiment(experiment)

        # Merge experiment metadata
        run_metadata = dict(experiment.metadata)
        run_metadata["experiment_id"] = experiment.experiment_id

        # Delegate execution to EvaluationRunner
        summary = self.runner.run(
            task=experiment.task,
            candidates=experiment.candidates,
            metadata=run_metadata,
        )

        result = ExperimentRunResult(
            experiment_id=experiment.experiment_id,
            summary=summary,
            metadata=dict(experiment.metadata),
        )
        return validate_experiment_run_result(result)
